"""Единый набор «пустых» значений для правил и верификатора.

Раньше RuleChecker и IssueVerifier использовали разные списки, из-за чего
валидные замечания (например, по занятости «любой») отбрасывались.
"""

from __future__ import annotations

MISSING_VALUES: frozenset[str] = frozenset(
    {
        "-",
        "—",
        "–",
        "нет",
        "нет данных",
        "нет информации",
        "не указано",
        "не указан",
        "не указана",
        "не указаны",
        "не указана информация",
        "не требуется",
        "не требуются",
        "не важно",
        "не важна",
        "любой",
        "любая",
        "любые",
        "отсутствует",
        "отсутствуют",
        "не заполнено",
        "не заполнен",
        "не применимо",
        "не предъявляются",
        "не предъявляется",
        "n/a",
        "na",
        "unknown",
        "неизвестно",
        "по договоренности",
        "по договорённости",
        "по результатам собеседования",
        "по итогам собеседования",
        "обсуждается",
        "оговаривается",
    },
)

_TRIM_CHARS = " \t\r\n.;:—–-"


def is_missing(value: str | None) -> bool:
    """True, если значение пустое или является заглушкой («не указано», «любой» и т.п.)."""
    if value is None:
        return True
    text = value.strip().lower().strip(_TRIM_CHARS)
    return not text or text in MISSING_VALUES
