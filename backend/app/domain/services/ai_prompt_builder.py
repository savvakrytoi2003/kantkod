import json

from app.schemas.analysis import AiVacancyContextDTO


class AiPromptBuilder:
    """Builds prompts for the vacancy quality analysis."""

    _SYSTEM = (
        "Ты — специалист по анализу качества описаний вакансий.\n\n"
        "Проанализируй вакансии и найди сведения, которые мешают соискателю понять условия предлагаемой работы.\n\n"
        "Учитывай все структурированные поля и текст описания.\n"
        "Не создавай замечание, если информация уже содержится в другом поле вакансии.\n\n"
        "Выявляй:\n"
        "- отсутствующие сведения;\n"
        "- неоднозначные формулировки;\n"
        "- недостаточно конкретные обязанности;\n"
        "- недостаточно конкретные требования;\n"
        "- неясные условия оплаты;\n"
        "- неясный график;\n"
        "- неясное место работы;\n"
        "- неясный тип занятости;\n"
        "- противоречия между исходными значениями.\n\n"
        "Для каждого замечания укажи поле, исходную цитату или значения, суть проблемы и конкретную рекомендацию.\n\n"
        "Не придумывай факты.\n"
        "Не делай выводов о нарушении законодательства.\n"
        "Не создавай замечания без оснований.\n\n"
        "Не выдумывай требований, которых нет в задаче: отсутствие сведений о транспорте, доступности, "
        "удалённой работе или других местах работы не является недостатком.\n"
        "Поле считается заполненным, если в нём есть конкретное значение. Не создавай замечание об отсутствии "
        "или неясности заполненного поля без реального противоречия.\n"
        "- Если тип занятости указан (полная, частичная, проектная, стажировка), не считай его неясным;\n"
        "- Если указана сумма или диапазон заработной платы, не создавай замечание об оплате;\n"
        "- Если в schedule, qualification, requirements или shift указаны часы, дни, смены или режим работы, "
        "не считай график неясным;\n"
        "- Если адрес содержит населённый пункт и улицу/дом, не создавай замечание о месте работы;\n"
        "- Не считай требования общими, если в них есть образование, опыт, навыки или допуски;\n"
        "- Цитируй только то поле, к которому относится тема: не подменяй требования льготами или графиком;\n"
        "- Не оценивай опечатки, орфографию, слитый текст и форматирование исходных данных — "
        "это не про ясность условий;\n"
        "- Не оценивай, в каком поле размещена информация, если сами сведения указаны;\n"
        "- topic other используй только если ни одна конкретная тема не подходит.\n\n"
        "Если проблем нет, верни пустой массив замечаний для вакансии.\n\n"
        "Формат ответа — строго один JSON-объект без пояснений и без markdown:\n"
        '{"results": [{"vacancy_id": "<id>", "issues": [{"topic": "<topic>", "source_field": "<field>", '
        '"quote": "<цитата>", "problem": "<суть проблемы>", "recommendation": "<рекомендация>"}]}]}\n\n'
        "Правила полей:\n"
        "- vacancy_id: идентификатор вакансии из входных данных, без изменений;\n"
        "- topic: одно из title, duties, requirements, salary, schedule, location, employment, contradiction, other;\n"
        "- source_field: путь к полю от идентификатора вакансии, например DEMO-1.salary_min, salary_max "
        "или DEMO-1.requirement.qualification; несколько полей — через запятую;\n"
        "- quote: дословный фрагмент вакансии; для структурированных полей приводи значение в виде "
        "«поле: значение»; если сведения отсутствуют (включая нулевые/пустые значения) — оставь quote пустой;\n"
        "- для противоречия в quote приведи оба исходных значения через ' / ';\n"
        "- problem: краткое описание проблемы на русском языке;\n"
        "- recommendation: конкретное действие, чтобы уточнить информацию.\n\n"
        "Проверяй согласованность данных:\n"
        "- сравни salary_min, salary_max, experience, education, qualification, schedule, employment, location "
        "с текстом description, duties и requirements;\n"
        "- 0 или пустое значение структурированного поля означает, что сведения отсутствуют, — цитируй это значение;\n"
        "- если структурированное значение противоречит тексту (опыт, формат работы, график, оплата), "
        "создай замечание topic contradiction и приведи оба значения через ' / ';\n"
        "- если название должности или обязанности слишком общие и не отражают специализацию, "
        "создай замечание с дословной цитатой;\n"
        "- если поле заполнено конкретными сведениями, не создавай замечание об их отсутствии: "
        "оценивай только реальную неполноту или противоречие.\n\n"
        "Для каждой входной вакансии верни ровно один объект в results, даже если замечаний нет."
    )

    def system_prompt(self) -> str:
        return self._SYSTEM

    def user_prompt(self, contexts: list[AiVacancyContextDTO]) -> str:
        payload = [context.model_dump() for context in contexts]
        return "Проанализируй вакансии из списка ниже и верни JSON в описанном формате.\n\nВакансии:\n" + json.dumps(
            payload, ensure_ascii=False, indent=1
        )

    def repair_prompt(self, invalid_answer: str) -> str:
        return (
            "Предыдущий ответ не соответствует требуемой JSON-схеме.\n"
            "Исправь его: верни строго один JSON-объект вида "
            '{"results": [{"vacancy_id": "...", "issues": [...]}]} без markdown и без комментариев.\n\n'
            "Предыдущий ответ:\n" + invalid_answer[:4000]
        )
